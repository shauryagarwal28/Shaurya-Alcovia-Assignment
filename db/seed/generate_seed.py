def q(v):
    if v is None: return "NULL"
    if isinstance(v, bool): return "true" if v else "false"
    if isinstance(v, (int, float)): return repr(round(v, 4)) if isinstance(v, float) else str(v)
    if isinstance(v, (dt.date, dt.datetime)) and not isinstance(v, dt.datetime): return f"DATE '{v.isoformat()}'"
    if isinstance(v, dt.datetime): return f"TIMESTAMPTZ '{v.strftime('%Y-%m-%d %H:%M:%S')}{IST}'"
    if isinstance(v, dict): return "'" + json.dumps(v).replace("'", "''") + "'::jsonb"
    return "'" + str(v).replace("'", "''") + "'"

