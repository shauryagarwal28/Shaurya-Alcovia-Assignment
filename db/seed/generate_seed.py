SEQ = {}
def emit(table, cols, rows, identity=None, chunk=200):
    if not rows: return
    ov = " OVERRIDING SYSTEM VALUE" if identity else ""
    for i in range(0, len(rows), chunk):
        part = rows[i:i + chunk]
        lines.append(f"INSERT INTO {table} ({', '.join(cols)}){ov} VALUES")
        lines.append(",\n".join("  (" + ", ".join(q(v) for v in r) + ")" for r in part) + ";")
    if identity: SEQ[table] = identity

